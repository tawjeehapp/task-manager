/**
 * Generate PWA icons + iOS splash screens from public/brand/logo.png
 * Run: node scripts/generate-pwa-assets.mjs
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const logoPath = path.join(root, "public/brand/logo.png");
const iconsDir = path.join(root, "public/icons");
const splashDir = path.join(root, "public/splash");

/** Brand teal — matches themeColor / sidebar */
const BG = { r: 0, g: 39, b: 35, alpha: 1 };

async function composeIcon(size, logoRatio) {
  const logoSize = Math.round(size * logoRatio);
  const logo = await sharp(logoPath)
    .resize(logoSize, logoSize, {
      fit: "contain",
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .png()
    .toBuffer();

  const left = Math.round((size - logoSize) / 2);
  const top = Math.round((size - logoSize) / 2);

  return sharp({
    create: {
      width: size,
      height: size,
      channels: 4,
      background: BG,
    },
  })
    .composite([{ input: logo, left, top }])
    .png()
    .toBuffer();
}

async function composeSplash(width, height) {
  const logoSize = Math.round(Math.min(width, height) * 0.28);
  const logo = await sharp(logoPath)
    .resize(logoSize, logoSize, {
      fit: "contain",
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .png()
    .toBuffer();

  const left = Math.round((width - logoSize) / 2);
  const top = Math.round((height - logoSize) / 2);

  return sharp({
    create: {
      width,
      height,
      channels: 4,
      background: BG,
    },
  })
    .composite([{ input: logo, left, top }])
    .png()
    .toBuffer();
}

/** Common iOS splash sizes (portrait). Landscape generated by swap. */
const SPLASH_PORTRAIT = [
  { name: "iphone-16-pro-max", w: 1320, h: 2868 },
  { name: "iphone-16-pro", w: 1206, h: 2622 },
  { name: "iphone-15-pro-max", w: 1290, h: 2796 },
  { name: "iphone-14-pro", w: 1179, h: 2556 },
  { name: "iphone-14", w: 1170, h: 2532 },
  { name: "iphone-xr", w: 828, h: 1792 },
  { name: "iphone-8-plus", w: 1242, h: 2208 },
  { name: "iphone-se", w: 750, h: 1334 },
  { name: "ipad-pro-12-9", w: 2048, h: 2732 },
  { name: "ipad-pro-11", w: 1668, h: 2388 },
  { name: "ipad-10-2", w: 1620, h: 2160 },
];

async function main() {
  await mkdir(iconsDir, { recursive: true });
  await mkdir(splashDir, { recursive: true });

  const assets = [
    ["icon-192.png", await composeIcon(192, 0.72)],
    ["icon-512.png", await composeIcon(512, 0.72)],
    ["icon-512-maskable.png", await composeIcon(512, 0.55)],
    ["apple-touch-icon.png", await composeIcon(180, 0.72)],
    ["icon-32.png", await composeIcon(32, 0.78)],
  ];

  for (const [name, buf] of assets) {
    await writeFile(path.join(iconsDir, name), buf);
    console.log("wrote", `public/icons/${name}`);
  }

  // favicon.ico via 32png is enough for modern browsers; also copy as favicon.png
  await writeFile(
    path.join(root, "public/favicon.ico"),
    await composeIcon(32, 0.78),
  );
  console.log("wrote public/favicon.ico");

  for (const { name, w, h } of SPLASH_PORTRAIT) {
    const portrait = await composeSplash(w, h);
    const landscape = await composeSplash(h, w);
    await writeFile(path.join(splashDir, `${name}.png`), portrait);
    await writeFile(path.join(splashDir, `${name}-landscape.png`), landscape);
    console.log("wrote", `public/splash/${name}.png (+ landscape)`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
